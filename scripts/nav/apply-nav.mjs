// Applies the canonical header from nav.mjs to every static page and the Insights templates,
// and points pages at /assets/site-nav.{css,js}. Safe to re-run.
// Usage (from the repo root): node scripts/nav/apply-nav.mjs
import fs from 'node:fs';
import path from 'node:path';
import { renderNav } from './nav.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const SKIP = new Set(['.git', 'node_modules', 'functions']);
// Pages that deliberately have no header (form confirmation).
const NO_HEADER = new Set(['contact-success.html']);
const CSS = '<link rel="preload" href="/assets/fonts/manrope-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin>\n<link rel="stylesheet" href="/assets/site-nav.css">';
const JS = '<script src="/assets/site-nav.js" defer></script>';

function walk(dir, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
}

function urlPathFor(file) {
  const rel = path.relative(ROOT, file).split(path.sep).join('/');
  if (rel.startsWith('scripts/templates/')) return '/insights/';
  return '/' + rel;
}

// The header always sits outside the page's .wrap container so its background spans the full width
// and it can stay sticky for the whole page.
const header = (urlPath) =>
  `<!-- mc-nav: generated by scripts/nav/apply-nav.mjs -->\n<div class="mc-header"><div class="wrap">${renderNav(urlPath)}</div></div>\n<!-- /mc-nav -->`;

let changed = 0;
const problems = [];
for (const file of walk(ROOT)) {
  if (file.includes(`${path.sep}scripts${path.sep}`) && !file.includes(`${path.sep}templates${path.sep}`)) continue;
  if (NO_HEADER.has(path.relative(ROOT, file))) continue;
  let html = fs.readFileSync(file, 'utf8');
  const before = html;
  const urlPath = urlPathFor(file);

  const navRe = '<nav class="nav"[^>]*>[\\s\\S]*?<\\/nav>';
  if (html.includes('<!-- mc-nav')) {
    html = html.replace(/<!-- mc-nav[^>]*-->[\s\S]*?<!-- \/mc-nav -->/, header(urlPath));
  } else if (new RegExp(`<div class="wrap">\\s*${navRe}\\s*<\\/div>`).test(html)) {
    // <div class="wrap"><nav>…</nav></div>  →  header
    html = html.replace(new RegExp(`<div class="wrap">\\s*${navRe}\\s*<\\/div>`), header(urlPath));
  } else if (new RegExp(`<div class="wrap">\\s*${navRe}`).test(html)) {
    // Page-level wrap that starts with the nav: lift the header out, keep the wrap for the content.
    html = html.replace(new RegExp(`<div class="wrap">\\s*${navRe}`), `${header(urlPath)}\n<div class="wrap">`);
  } else if (new RegExp(navRe).test(html)) {
    html = html.replace(new RegExp(navRe), header(urlPath));
    problems.push(`nav not inside .wrap (check layout): ${path.relative(ROOT, file)}`);
  } else {
    problems.push(`no nav found: ${path.relative(ROOT, file)}`);
  }

  // Stylesheet + font preload
  if (!html.includes('/assets/site-nav.css')) {
    if (html.includes('<link rel="stylesheet" href="/assets/services-dropdown.css">')) html = html.replace('<link rel="stylesheet" href="/assets/services-dropdown.css">', CSS);
    else html = html.replace('</head>', `${CSS}\n</head>`);
  }
  html = html.replace(/\s*<link rel="stylesheet" href="\/assets\/services-dropdown\.css">/g, '');
  // Script
  if (!html.includes('/assets/site-nav.js')) {
    if (html.includes('<script src="/assets/services-dropdown.js" defer></script>')) html = html.replace('<script src="/assets/services-dropdown.js" defer></script>', JS);
    else html = html.replace('</body>', `${JS}\n</body>`);
  }
  html = html.replace(/\s*<script src="\/assets\/services-dropdown\.js" defer><\/script>/g, '');

  if (html !== before) { fs.writeFileSync(file, html); changed++; }
}
console.log(`apply-nav: updated ${changed} files`);
if (problems.length) { console.error(problems.join('\n')); process.exitCode = 1; }
